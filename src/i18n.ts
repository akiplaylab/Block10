export type Language = 'en' | 'ja';
export type Message = keyof typeof en;

export function isLanguage(value: unknown): value is Language {
  return value === 'en' || value === 'ja';
}

export function browserLanguage(preference?: string): Language {
  return /^ja(?:-|$)/i.test(preference ?? '') ? 'ja' : 'en';
}

export function translate(language: Language, key: Message, values: Record<string, string | number> = {}) {
  const message = (language === 'ja' ? ja[key] : undefined) ?? en[key];
  return message.replace(/\{(\w+)\}/g, (placeholder, name: string) => String(values[name] ?? placeholder));
}
